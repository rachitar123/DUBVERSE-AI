# ── Pydantic models ────────────────────────────────────────────────────────────

class ConversationTurn(BaseModel):
    role: str          # "user" or "assistant"
    content: str


class TranscriptSegmentCtx(BaseModel):
    """A single transcript segment from the existing pipeline — no DB changes."""
    segment_index: int
    start_time: float
    end_time: float
    original_text: str
    translated_text: Optional[str] = None
    speaker: Optional[str] = None


class ProjectContext(BaseModel):
    project_id: Optional[int] = None
    project_title: Optional[str] = None
    source_language: Optional[str] = None
    target_language: Optional[str] = None
    voice_name: Optional[str] = None
    status: Optional[str] = None
    processing_stage: Optional[str] = None
    progress: Optional[int] = None
    error_message: Optional[str] = None
    duration_seconds: Optional[float] = None
    segments_count: Optional[int] = None
    # Transcript segments from the existing Whisper pipeline
    transcript_segments: Optional[List[TranscriptSegmentCtx]] = None


class ChatRequest(BaseModel):
    message: str
    conversation_history: Optional[List[ConversationTurn]] = []
    project_context: Optional[ProjectContext] = None


class ChatResponse(BaseModel):
    response: str
    has_transcript: bool = False


# ── Transcript formatting helpers ──────────────────────────────────────────────

def _fmt_time(seconds: float) -> str:
    """Convert float seconds to MM:SS string."""
    m = int(seconds // 60)
    s = int(seconds % 60)
    return f"{m:02d}:{s:02d}"


def format_transcript(segments: List[TranscriptSegmentCtx]) -> str:
    """
    Format transcript segments into a readable text block with timestamps.
    Uses original_text (source language) as the speech content.
    """
    lines = []
    for seg in segments:
        timestamp = f"[{_fmt_time(seg.start_time)} → {_fmt_time(seg.end_time)}]"
        speaker = f"({seg.speaker})" if seg.speaker and seg.speaker != "Speaker 1" else ""
        text = seg.original_text.strip()
        lines.append(f"{timestamp} {speaker} {text}".strip())
    return "\n".join(lines)


# ── Simple chunk retrieval for long transcripts ────────────────────────────────

# If transcript exceeds this many characters, use chunk selection
TRANSCRIPT_CHAR_THRESHOLD = 6000
CHUNK_SIZE_SEGMENTS = 5          # segments per chunk
TOP_K_CHUNKS = 4                 # how many top chunks to include


def _tokenize(text: str) -> set:
    """Simple word tokenizer for keyword overlap scoring."""
    return set(re.findall(r'\b[a-zA-Z]{3,}\b', text.lower()))


def select_relevant_chunks(
    segments: List[TranscriptSegmentCtx],
    query: str,
    conversation_history: List[ConversationTurn],
) -> List[TranscriptSegmentCtx]:
    """
    Split segments into chunks and select the most relevant ones
    using keyword overlap between query+history and chunk text.
    Always include the first and last chunk for context anchoring.
    """
    if not segments:
        return []

    # Build query tokens from message + last few conversation turns
    combined_query = query
    for turn in conversation_history[-4:]:
        combined_query += " " + turn.content
    query_tokens = _tokenize(combined_query)

    # Split into chunks of CHUNK_SIZE_SEGMENTS
    chunks: List[List[TranscriptSegmentCtx]] = []
    for i in range(0, len(segments), CHUNK_SIZE_SEGMENTS):
        chunks.append(segments[i : i + CHUNK_SIZE_SEGMENTS])

    if len(chunks) <= TOP_K_CHUNKS + 2:
        # Short enough — return everything
        return segments

    # Score each chunk by keyword overlap
    scored = []
    for idx, chunk in enumerate(chunks):
        chunk_text = " ".join(s.original_text for s in chunk)
        chunk_tokens = _tokenize(chunk_text)
        overlap = len(query_tokens & chunk_tokens)
        scored.append((idx, overlap))

    scored.sort(key=lambda x: x[1], reverse=True)
    top_indices = set(x[0] for x in scored[:TOP_K_CHUNKS])

    # Always include first and last chunk for context grounding
    top_indices.add(0)
    top_indices.add(len(chunks) - 1)

    # Reconstruct in order
    result = []
    for idx in sorted(top_indices):
        result.extend(chunks[idx])
    return result


def prepare_transcript_for_prompt(
    segments: List[TranscriptSegmentCtx],
    query: str,
    history: List[ConversationTurn],
) -> str:
    """
    Decide whether to use the full transcript or a retrieved subset,
    then format with timestamps.
    """
    full_text = " ".join(s.original_text for s in segments)
    if len(full_text) <= TRANSCRIPT_CHAR_THRESHOLD:
        selected = segments
        note = ""
    else:
        selected = select_relevant_chunks(segments, query, history)
        note = f"\n[NOTE: Showing {len(selected)} of {len(segments)} transcript segments most relevant to your question. Full transcript has {len(segments)} segments.]\n"
    return note + format_transcript(selected)


# ── System prompt ──────────────────────────────────────────────────────────────

SYSTEM_PROMPT_BASE = """You are DubVerse AI Assistant — a VIDEO-AWARE AI assistant built into the DubVerse professional video dubbing platform.

You have TWO main capabilities:

═══════════════════════════════════════════════════════════
1. VIDEO CONTENT ASSISTANT (Primary)
═══════════════════════════════════════════════════════════
When a video transcript is provided, you can answer ANY question about the video content:
- "What is this video about?"
- "Summarize the video."
- "What are the main points?"
- "What did the speaker say about X?"
- "Did they mention Y?"
- "What was discussed at the beginning/end?"
- "What examples or advantages were mentioned?"
- "Who or what is mentioned in the video?"
- "What is the speaker's main argument?"
- Conversational follow-ups referencing previous answers

TRANSCRIPT RULES:
- Base your answers ONLY on the provided transcript content.
- When transcript timestamps are available, reference them (e.g. "Around 00:32, the speaker...").
- If the answer is not in the transcript, say clearly: "I couldn't find that information in this video's transcript."
- Do NOT invent information, quotes, or facts not present in the transcript.
- For visual questions (colors, what's on screen, number of people visible) that cannot be answered from audio transcript alone, honestly say: "The transcript doesn't contain visual information needed to answer that."
- Maintain conversation context — if the user says "explain the second one", refer to your previous response.

═══════════════════════════════════════════════════════════
2. DUBVERSE APPLICATION ASSISTANT (Secondary)
═══════════════════════════════════════════════════════════
You also help users understand and operate the DubVerse dubbing workflow:
- Transcription: AI speech recognition using Whisper
- Translation: LLM-based text translation
- Text-to-Speech (TTS): AI voice synthesis using ElevenLabs / Inworld
- Voice Selection: Choosing the right voice for target language and content
- Synchronization: Aligning dubbed audio with original video timeline
- Full pipeline: Video → Audio Extraction → Whisper Transcription → Translation → Voice Synthesis → A/V Sync → Final Dubbed Video
- Troubleshooting failures at each stage
- Error explanation: what it means, why it happened, what to do next

PROJECT RULES:
- Use provided project context (status, language, error) for specific answers.
- Do NOT invent project data not in the context.
- If error is provided, explain: (1) what it means (2) why it happened (3) what to do.

═══════════════════════════════════════════════════════════
GENERAL RULES (both modes)
═══════════════════════════════════════════════════════════
- Determine user intent naturally — don't ask the user to specify their intent.
- Keep answers concise, practical, and friendly.
- Use bullet points or numbered lists for multi-part answers.
- Use clear language without jargon.
- Respond in the same language the user writes in.
- NEVER expose API keys, passwords, tokens, or internal secrets.
- NEVER claim to have performed an action you did not actually perform.
- If asked something completely unrelated to video/dubbing, politely redirect.
"""


def build_system_prompt(
    ctx: Optional[ProjectContext],
    query: str,
    history: List[ConversationTurn],
) -> str:
    prompt = SYSTEM_PROMPT_BASE

    if not ctx:
        return prompt

    # ── Project metadata block ─────────────────────────────────────────────────
    meta_block = "\n\n══════════════════════════════════════\nCURRENT PROJECT CONTEXT\n══════════════════════════════════════\n"
    if ctx.project_id:
        meta_block += f"Project ID: #{ctx.project_id}\n"
    if ctx.project_title:
        meta_block += f"Project Title: {ctx.project_title}\n"
    if ctx.source_language:
        meta_block += f"Source Language: {ctx.source_language}\n"
    if ctx.target_language:
        meta_block += f"Target Language: {ctx.target_language}\n"
    if ctx.voice_name:
        meta_block += f"Selected Voice: {ctx.voice_name}\n"
    if ctx.status:
        meta_block += f"Current Status: {ctx.status}\n"
    if ctx.processing_stage:
        meta_block += f"Processing Stage: {ctx.processing_stage}\n"
    if ctx.progress is not None:
        meta_block += f"Progress: {ctx.progress}%\n"
    if ctx.duration_seconds:
        meta_block += f"Video Duration: {ctx.duration_seconds:.1f} seconds\n"
    if ctx.segments_count:
        meta_block += f"Total Transcript Segments: {ctx.segments_count}\n"
    if ctx.error_message:
        meta_block += f"Error Message: {ctx.error_message}\n"
    meta_block += "══════════════════════════════════════\n"
    prompt += meta_block

    # ── Transcript block ──────────────────────────────────────────────────────
    if ctx.transcript_segments:
        transcript_text = prepare_transcript_for_prompt(
            ctx.transcript_segments, query, history
        )
        transcript_block = (
            "\n\n══════════════════════════════════════\n"
            "VIDEO TRANSCRIPT (from Whisper speech recognition)\n"
            "Format: [MM:SS → MM:SS] spoken text\n"
            "══════════════════════════════════════\n"
            f"{transcript_text}\n"
            "══════════════════════════════════════\n\n"
            "The above is the ACTUAL transcript of the video. "
            "Use it to answer any questions about the video content. "
            "Reference timestamps when relevant.\n"
        )
        prompt += transcript_block
    elif ctx.status in ("COMPLETED", "TRANSLATING", "SYNTHESIZING", "SYNCING"):
        prompt += (
            "\n\nNOTE: This project's transcript segments were not included in this request. "
            "If the user asks about the video content, let them know the transcript context is unavailable for this query.\n"
        )

    return prompt


# ── Chatbot endpoint ───────────────────────────────────────────────────────────

@router.post("/message", response_model=ChatResponse)
def chat_message(
    request: ChatRequest,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    """
    Process a user message and return a video-aware AI response.
    Reuses existing Whisper transcript data — no second transcription pipeline.
    Uses the existing GEMINI_API_KEY — no new credentials required.
    """
    if not GEMINI_API_KEY:
        logger.error("GEMINI_API_KEY is not configured.")
        raise HTTPException(
            status_code=503,
            detail="AI service is not configured. Please set GEMINI_API_KEY in backend/.env",
        )

    user_message = request.message.strip()
    if not user_message:
        raise HTTPException(status_code=400, detail="Message cannot be empty.")

    has_transcript = bool(
        request.project_context
        and request.project_context.transcript_segments
    )

    try:
        import google.generativeai as genai  # already in requirements.txt

        genai.configure(api_key=GEMINI_API_KEY)

        system_prompt = build_system_prompt(
            request.project_context,
            user_message,
            request.conversation_history or [],
        )

        # Build conversation history (Gemini expects alternating user/model turns)
        history = []
        for turn in (request.conversation_history or []):
            role = "model" if turn.role == "assistant" else "user"
            history.append({"role": role, "parts": [turn.content]})

        model = genai.GenerativeModel(
            model_name="gemini-3.8-flash",
            system_instruction=system_prompt,
        )

        chat = model.start_chat(history=history)
        response = chat.send_message(user_message)

        ai_text = response.text.strip()
        return ChatResponse(response=ai_text, has_transcript=has_transcript)

    except HTTPException:
        raise
    except Exception as exc:
        # Log the real error server-side only — never expose to client
        logger.error(
            "Chatbot Gemini API error for user %s: %s",
            current_user.id, exc, exc_info=True,
        )
        raise HTTPException(
            status_code=502,
            detail="AI service temporarily unavailable. Please try again.",
        )
